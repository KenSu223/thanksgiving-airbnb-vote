function Face({ kind }) {
  const s = kind[0], n = Number(kind[1]);
  if (s === 'm') return <><span className="mj-cn">{CN[n - 1]}</span><span className="mj-wan">萬</span></>;
  return (
    <svg viewBox="0 0 30 40" className="mj-svg" aria-hidden="true">
      {s === 'p'
        ? DOTS[n].map(([x, y, r], i) => (
          <g key={i}>
            <circle cx={x} cy={y} r={r} fill="none" stroke={n === 1 ? '#dc2626' : '#1d4ed8'} strokeWidth={r > 6 ? 2.2 : 1.6} />
            <circle cx={x} cy={y} r={r * 0.42} fill={n === 1 || (n === 5 && i === 2) || (n === 9 && i >= 3 && i <= 5) ? '#dc2626' : '#15803d'} />
          </g>
        ))
        : STICKS[n].map(([x, y, h, red], i) => (
          <g key={i}>
            <rect x={x - 1.9} y={y - h / 2} width={3.8} height={h} rx={1.9} fill={red ? '#dc2626' : '#15803d'} />
            <rect x={x - 1.9} y={y - 0.6} width={3.8} height={1.2} fill="#fff" opacity=".7" />
          </g>
        ))}
    </svg>
  );
}

// inline：放在一行字里的牌（「胡了 X 打的 [三萬]」、按钮上的牌），跟着字走，不另起一行
// slam：刚打出去的牌——拍到桌上，底下扬起一点灰（只在牌出现的那一下播；挂上去时才算，所以要换 key 才会再播）
export default function MjTile({ kind, size = '', selected, lit, inline, slam, className = '', ...rest }) {
  const Tag = rest.onClick ? 'button' : inline ? 'span' : 'div';
  return (
    <Tag {...rest} className={'mj-tile ' + size + (kind ? '' : ' back') + (selected ? ' sel' : '') + (lit ? ' lit' : '') + (inline ? ' inline' : '') + (slam ? ' slam' : '') + (className ? ' ' + className : '')}>
      {kind && <Face kind={kind} />}
      {slam && <span className="mj-dust" aria-hidden="true"><i /><i /><i /><i /><i /><i /></span>}
    </Tag>
  );
}
