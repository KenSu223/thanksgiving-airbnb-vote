function Face({ kind }) {
  const s = kind[0], n = Number(kind[1]);
  if (s === 'm') return <><span className="mj-cn">{CN[n - 1]}</span><span className="mj-wan">萬</span></>;
  return (
    <svg viewBox="0 0 30 40" className="mj-svg" aria-hidden="true">
      {s === 'p'
        ? DOTS[n].map(([x, y, r, c], i) => (
          <g key={i}>
            {/* 一筒是个大饼：外圈绿，里面红 */}
            <circle cx={x} cy={y} r={r} fill={n === 1 ? G : c} />
            <circle cx={x} cy={y} r={r * 0.68} fill="#fffdf6" />
            <circle cx={x} cy={y} r={r * 0.42} fill={c} />
            {n === 1 && <circle cx={x} cy={y} r={r * 0.16} fill="#fffdf6" />}
          </g>
        ))
        : STICKS[n].map(([x, y, h, c, tilt], i) => (
          <g key={i} transform={tilt ? `rotate(${tilt} ${x} ${y})` : undefined}>
            <rect x={x - 1.9} y={y - h / 2} width={3.8} height={h} rx={1.9} fill={c} />
            <rect x={x - 1.9} y={y - 0.6} width={3.8} height={1.2} fill="#fff" opacity=".7" />
          </g>
        ))}
    </svg>
  );
}

// inline：放在一行字里的牌（「胡了 X 打的 [三萬]」、按钮上的牌），跟着字走，不另起一行
// slam：刚打出去的牌——拍到桌上，底下扬起一点灰（只在牌出现的那一下播；挂上去时才算，所以要换 key 才会再播）
// badge：牌左上角的小字（手牌里「打这张就听」标「听」）
export default function MjTile({ kind, size = '', selected, lit, inline, slam, badge, className = '', ...rest }) {
  const Tag = rest.onClick ? 'button' : inline ? 'span' : 'div';
  return (
    <Tag {...rest} data-kind={kind || undefined} className={'mj-tile ' + size + (kind ? '' : ' back') + (selected ? ' sel' : '') + (lit ? ' lit' : '') + (inline ? ' inline' : '') + (slam ? ' slam' : '') + (className ? ' ' + className : '')}>
      {kind && <Face kind={kind} />}
      {badge && <span className="mj-badge" aria-hidden="true">{badge}</span>}
      {slam && <span className="mj-dust" aria-hidden="true"><i /><i /><i /><i /><i /><i /></span>}
    </Tag>
  );
}
